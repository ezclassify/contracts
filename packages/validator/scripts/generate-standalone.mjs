#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';
import { buildSync } from 'esbuild';
import {
    accessSchema,
    contextSchema,
    crosswalkSchema,
    guideSchema,
    schemeSchema,
} from '@ezclassify/schemas';

const here = path.dirname(fileURLToPath(import.meta.url));
const outputDirectory = path.resolve(here, '../src/generated');
const check = process.argv.includes('--check');
const schemas = {
    access: accessSchema,
    context: contextSchema,
    crosswalk: crosswalkSchema,
    guide: guideSchema,
    scheme: schemeSchema,
};

function generate(kind, schema) {
    const dialect = String(schema?.$schema ?? '');
    const Constructor = dialect.includes('2020-12') ? Ajv2020 : Ajv;
    const ajv = new Constructor({
        allErrors: true,
        strict: false,
        code: { esm: true, lines: true, source: true },
    });
    addFormats(ajv);
    const standalone = standaloneCode(ajv, ajv.compile(schema));
    // Ajv's ESM standalone output uses one static CommonJS require for its
    // Unicode length helper. Bundle that official helper into the module so
    // the shipped validator has no package lookup and remains browser/CSP safe.
    const build = buildSync({
        absWorkingDir: path.resolve(here, '..'),
        bundle: true,
        format: 'esm',
        logLevel: 'silent',
        platform: 'browser',
        stdin: {
            contents: standalone,
            // Resolve Ajv's generated helper import from this package, not the
            // caller's working directory, so write/check output is identical
            // from the repo root and through an npm workspace command.
            resolveDir: path.resolve(here, '..'),
            sourcefile: `${kind}.validator.mjs`,
        },
        target: 'es2022',
        write: false,
    });
    const body = build.outputFiles[0].text
        // Esbuild labels stdin relative to the caller's cwd. The label is not
        // executable or attribution content, so omit it to keep generation
        // deterministic from either the repo root or npm's workspace cwd.
        .replace(/^\/\/ .*\.validator\.mjs\n/, '')
        .replace(/^\s*ucs2length\.code\s*=\s*['"][^\n]*['"];?\s*$/gm, '');
    for (const forbidden of [
        /\brequire\s*\(/,
        /\bimport\s*\(/,
        /\bnew Function\b/,
        /\beval\s*\(/,
        /node:/,
    ]) {
        if (forbidden.test(body)) {
            throw new Error(
                `${kind} standalone validator contains forbidden runtime code: ${forbidden}`,
            );
        }
    }
    return (
        `// Generated by packages/validator/scripts/generate-standalone.mjs.\n` +
        `// Source: @ezclassify/schemas ${kind} schema. Do not edit.\n` +
        body
    );
}

mkdirSync(outputDirectory, { recursive: true });
const stale = [];
for (const [kind, schema] of Object.entries(schemas)) {
    const file = path.join(outputDirectory, `${kind}.validator.mjs`);
    const generated = generate(kind, schema);
    if (check) {
        let current = '';
        try {
            current = readFileSync(file, 'utf8');
        } catch {
            // Report the missing file through the same freshness result.
        }
        if (current !== generated)
            stale.push(path.relative(process.cwd(), file));
    } else {
        writeFileSync(file, generated, 'utf8');
    }
}

if (stale.length > 0) {
    process.stderr.write(
        `Standalone validators are stale:\n${stale.map((file) => `  ${file}`).join('\n')}\n` +
            'Run npm run generate:standalone -w @ezclassify/validator.\n',
    );
    process.exit(1);
}
